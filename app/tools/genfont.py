"""Bake the UI fonts into 4-bit anti-aliased bitmaps for the RGB565 renderer.

Output: src/ui/fonts.c (data) - the header is src/ui/fonts.h (hand written).
Fonts: Barlow Semi Condensed (OFL) for the UI, JetBrains Mono (OFL) for G-code.
Run from app/:  python tools/genfont.py
"""
import os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
FD = os.path.join(HERE, "fonts")
OUT = os.path.join(HERE, "..", "src", "ui", "fonts.c")

EXTRA = "−–—Ø°×·→←↑↓±✓…‹›µ²"
CHARS = sorted([chr(c) for c in range(32, 127)] + list(EXTRA), key=ord)

FONTS = [  # c name, file, px, variation
    ("font_12", "BarlowSemiCondensed-Medium.ttf", 13, None),
    ("font_14", "BarlowSemiCondensed-Medium.ttf", 15, None),
    ("font_16", "BarlowSemiCondensed-SemiBold.ttf", 17, None),
    ("font_20", "BarlowSemiCondensed-SemiBold.ttf", 21, None),
    ("font_28", "BarlowSemiCondensed-SemiBold.ttf", 30, None),
    ("font_40", "BarlowSemiCondensed-SemiBold.ttf", 44, None),
    ("font_mono", "JetBrainsMono.ttf", 13, b"Regular"),
]


def missing(f, ch):
    """True when the font has no real glyph for ch (it would draw .notdef)."""
    probe = chr(0xE000)  # private use: no font has it, so it renders .notdef
    return ch != " " and bytes(f.getmask(ch)) == bytes(f.getmask(probe))


def bake(name, fname, px, var):
    main = ImageFont.truetype(os.path.join(FD, fname), px)
    if var:
        try:
            main.set_variation_by_name(var)
        except Exception:
            pass
    # DejaVu (free licence, tools/fonts/LICENSE-DejaVu.txt) fills arrows and dashes Barlow lacks
    fb = ImageFont.truetype(os.path.join(FD, "DejaVuSans-Bold.ttf" if "Bold" in fname else "DejaVuSans.ttf"), int(px * 0.92))
    ascent, descent = main.getmetrics()
    fb_dy = ascent - fb.getmetrics()[0]
    glyphs, bits, cps = [], bytearray(), []
    for ch in CHARS:
        f, dy = main, 0
        if missing(main, ch):
            if missing(fb, ch):
                continue
            f, dy = fb, fb_dy
        adv = int(round(f.getlength(ch)))
        box = f.getbbox(ch)
        if box is None or box[2] <= box[0]:
            glyphs.append((0, 0, 0, 0, adv, len(bits)))
            cps.append(ord(ch))
            continue
        x0, y0, x1, y1 = box
        w, h = x1 - x0, y1 - y0
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255)
        px_ = im.tobytes()
        off = len(bits)
        row = []
        for i in range(0, len(px_)):
            row.append(px_[i] >> 4)
        if len(row) % 2:
            row.append(0)
        for i in range(0, len(row), 2):
            bits.append(row[i] << 4 | row[i + 1])
        glyphs.append((w, h, x0, y0 + dy, adv, off))
        cps.append(ord(ch))
    return ascent, descent, glyphs, bits, cps


def main():
    out = ['/* Generated by tools/genfont.py - do not edit. Fonts: Barlow Semi Condensed,',
           ' * JetBrains Mono, both SIL Open Font License 1.1 (tools/fonts/OFL-*.txt). */',
           '#include "fonts.h"', '']
    for name, fname, px, var in FONTS:
        asc, desc, gl, bits, cps = bake(name, fname, px, var)
        out.append(f"static const uint8_t {name}_bits[{max(1, len(bits))}] = {{")
        for i in range(0, len(bits), 24):
            out.append("  " + ",".join(str(b) for b in bits[i:i + 24]) + ",")
        out.append("};")
        out.append(f"static const glyph_t {name}_g[{len(gl)}] = {{")
        for g in gl:
            out.append("  {%d,%d,%d,%d,%d,%d}," % g)
        out.append("};")
        out.append(f"static const uint16_t {name}_cp[{len(cps)}] = {{" + ",".join(map(str, cps)) + "};")
        out.append(f"const font_t {name} = {{{asc + desc}, {asc}, {len(gl)}, {name}_g, {name}_cp, {name}_bits}};")
        out.append("")
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
