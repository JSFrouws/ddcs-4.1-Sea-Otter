"""Embed a file as a C byte string: embed.py <in> <out.c> <SYMBOL>"""
import sys

src, out, sym = sys.argv[1], sys.argv[2], sys.argv[3]
data = open(src, "rb").read()
with open(out, "w") as f:
    f.write("/* Generated by tools/embed.py from %s - do not edit. */\n" % src.replace("\\", "/"))
    f.write("const unsigned %s_LEN = %d;\nconst char %s[] = {\n" % (sym, len(data), sym))
    for i in range(0, len(data), 24):
        f.write("  " + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
    f.write("  0 };\n")
