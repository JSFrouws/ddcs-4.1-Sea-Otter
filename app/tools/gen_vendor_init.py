"""Turn the vendor app's captured FPGA start-up writes into a C table.
In:  ../docs/raw/2026-10-18_motion-probe/vendor_start_reads.log  (the time-stamped io trace of
     the vendor app's boot: 1192 writes between t=3.04 and t=4.11 s, reads in between)
Out: src/hal/fpga_vendor_init.c
fpga_init() replays it, but substitutes this machine's axis config / I/O ports from the
settings, opens the FPGA soft limits wide (ours are in software, and homing must pass
them), and skips the vendor's position restore (we keep the FPGA's own counters).

The PAUSES are part of the sequence (2026-11-02). The vendor waits 51 ms after releasing
0x44 (a reset line of the block-motion engine: 0 then 1), 50 and 250 ms after some 0x45
writes, and a few shorter gaps. Replayed back to back, the configuration that follows the
reset lands in an engine still coming up, and the result is silent: every block stream
still plays, but ~150 ms after a stream's last block the FPGA drops into its halted state
(queue reads 0x100, nothing plays until a power cycle). Bisected on the unit with
tools/blockmove.c INIT_FILE (write #56 of the table) and fixed by honouring the gaps; the
untimed vendor_init_writes.txt is the same sequence without them.
ALL the gaps, not just the long ones (2026-11-02, evening). The vendor's accesses are
200-300 us apart; ours were ~70 us (one ioctl). With only the gaps over 5 ms kept, the
same binary passed 5 cold boots in the afternoon and then failed 11 in a row, while the
same binary with a register trace switched on (a few tens of us more per access) passed
every time: the serial configuration is marginal at our pace. Every gap the vendor left
is now emitted (1191 of 1192 writes carry one; the init takes ~1.1 s instead of 0.3 s),
and with that 3 of 3 cold boots and 3 of 3 app restarts (a second init on a configured
FPGA, which halted 6 of 6 times before) stream cleanly.
The READS are part of it too (2026-11-02, measured on a freshly powered FPGA). The vendor
reads 0x40 after every strobe of its bit-banged serial configuration (0x47 data, 0x48=5,
read 0x40, 0x48=0; 250 times) plus a handful of status reads. The timed writes alone leave
a fresh FPGA poisoned (the first stream halts, queue 0x100); the same writes with the reads
in place stream cleanly, so does reading an unrelated register in their place, and a 70 us
pause in their place does NOT - the bus read transaction matters, not the time it takes.
An FPGA the vendor app initialised since power-up is immune, which is why the first tool
sessions never saw it. Reads between the first and the last write are emitted as rows
with read=1 (val is the value the vendor saw, for reference only)."""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(HERE, "..", "..", "docs", "raw", "2026-10-18_motion-probe", "vendor_start_reads.log")
out = os.path.join(HERE, "..", "src", "hal", "fpga_vendor_init.c")
MIN_GAP_S = 0.0   # every gap the vendor left (see above: 0.005 was not enough)
rows = []
prev = None
pending_reads = []
for line in open(src, encoding="utf-8", errors="replace"):
    m = re.match(r"t=([\d.]+)\s+([WR]) ([0-9a-f]+)=([0-9a-f]+)", line)
    if not m:
        continue
    t = float(m[1])
    kind, addr, val = m[2], int(m[3], 16), int(m[4], 16)
    if kind == "R":
        if prev is not None:                 # reads before the first write are not part of the init
            pending_reads.append((addr, val, 0, 1))
        continue
    rows.extend(pending_reads)
    pending_reads = []
    wait_us = int((t - prev) * 1e6) if prev is not None and t - prev >= MIN_GAP_S else 0
    prev = t
    rows.append((addr, val, wait_us, 0))
# reads after the last write (the vendor's idle polling) are dropped with pending_reads
with open(out, "w") as f:
    f.write("/* Generated by tools/gen_vendor_init.py from the vendor app's own start-up sequence,\n")
    f.write(" * captured on the unit 2026-10-18 (docs/raw/2026-10-18_motion-probe). Do not edit.\n")
    f.write(" * {addr, val, wait_us, read}: wait_us = the vendor's own pause BEFORE the access,\n")
    f.write(" * read = 1 for the vendor's register reads; both are required (see the tool). */\n")
    f.write('#include "fpga_vendor_init.h"\n\nconst fpga_init_write_t FPGA_VENDOR_INIT[] = {\n')
    for i in range(0, len(rows), 6):
        f.write("  " + " ".join("{0x%02x,0x%04x,%u,%u}," % r for r in rows[i:i + 6]) + "\n")
    f.write("};\nconst int FPGA_VENDOR_INIT_N = %d;\n" % len(rows))
print("wrote", out, len(rows), "rows:", sum(1 for r in rows if not r[3]), "writes,",
      sum(1 for r in rows if r[3]), "reads,", sum(1 for r in rows if r[2]), "with a pause")
