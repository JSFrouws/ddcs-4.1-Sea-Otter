"""Turn the vendor app's captured FPGA start-up writes into a C table.
In:  ../docs/raw/2026-10-18_motion-probe/vendor_init_writes.txt  ("aa=vvvv" per line, 1192 writes)
Out: src/hal/fpga_vendor_init.c
fpga_init() replays it, but substitutes this machine's axis config / I/O ports from the
settings, opens the FPGA soft limits wide (ours are in software, and homing must pass
them), and skips the vendor's position restore (we keep the FPGA's own counters)."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(HERE, "..", "..", "docs", "raw", "2026-10-18_motion-probe", "vendor_init_writes.txt")
out = os.path.join(HERE, "..", "src", "hal", "fpga_vendor_init.c")
pairs = []
for line in open(src):
    line = line.strip()
    if "=" in line:
        a, v = line.split("=")
        pairs.append((int(a, 16), int(v, 16)))
with open(out, "w") as f:
    f.write("/* Generated by tools/gen_vendor_init.py from the vendor app's own start-up writes,\n")
    f.write(" * captured on the unit 2026-10-18 (docs/raw/2026-10-18_motion-probe). Do not edit. */\n")
    f.write('#include <stdint.h>\n\nconst uint16_t FPGA_VENDOR_INIT[][2] = {\n')
    for i in range(0, len(pairs), 8):
        f.write("  " + " ".join("{0x%02x,0x%04x}," % p for p in pairs[i:i + 8]) + "\n")
    f.write("};\nconst int FPGA_VENDOR_INIT_N = %d;\n" % len(pairs))
print("wrote", out, len(pairs))
